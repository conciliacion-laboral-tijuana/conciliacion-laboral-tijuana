@register.simple_tag
def svg(name, size=None, class_name=None, **kwargs):
    """
    Renderiza un icono SVG inline.

    Uso:
        {% svg 'check' %}
        {% svg 'check' size='16' %}
        {% svg 'check' class_name='w-5 h-5 text-green-500' %}
        {% svg 'check' class_name='icon' data_attr='value' %}
    """
    if name not in ICONS:
        return mark_safe(f'<!-- icon "{name}" not found -->')

    viewBox, paths = ICONS[name]
    size_attr = f' width="{size}" height="{size}"' if size else ' width="24" height="24"'
    class_attr = f' class="{class_name}"' if class_name else ''

    # Additional HTML attributes
    extra_attrs = ''
    for k, v in kwargs.items():
        extra_attrs += f' {k.replace("_", "-")}="{v}"'

    inner = '\n        '.join(paths)
    svg_html = f'''<svg{size_attr}{class_attr}{extra_attrs} viewBox="{viewBox}" xmlns="http://www.w3.org/2000/svg">
        {inner}
    </svg>'''
    return mark_safe(svg_html)
